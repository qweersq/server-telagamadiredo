    /**
     * Generate billing for trial tenant
     */
    static async generateTrialBilling(tenantId) {
        try {
            console.log('🔍 BillingService.generateTrialBilling - Tenant ID:', tenantId);

            const TenantRepository = require('../repositories/tenantRepository');

            // Get tenant details
            const tenant = await TenantRepository.getById(tenantId);
            if (!tenant) {
                throw new Error('Tenant not found');
            }

            // Get default subscription plan (assuming plan ID 1 is the default)
            const SubscriptionPlanRepository = require('../repositories/subscriptionPlanRepository');
            const defaultPlan = await SubscriptionPlanRepository.getById(1);
            if (!defaultPlan) {
                throw new Error('Default subscription plan not found');
            }

            // Generate invoice number
            const invoiceNumber = await this.generateInvoiceNumber();

            // Get tenant's active subscription for trial billing
            const activeSubscription = await SubscriptionRepository.getActiveByTenantId(tenantId);

            // Create trial billing with subscription_id
            const billingData = {
                subscription_id: activeSubscription?.id || null, // Use subscription if available
                tenant_id: tenantId,
                amount: activeSubscription?.final_price || defaultPlan.price,
                status: 'pending',
                due_date: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // 7 days from now
                invoice_number: invoiceNumber,
                notes: `Trial billing - Upgrade to ${activeSubscription?.plan?.name || defaultPlan.name}`
            };

            const billing = await TenantPaymentRepository.create(billingData);
            console.log('✅ BillingService.generateTrialBilling - Created billing:', billing.id);

            return billing;
        } catch (error) {
            console.error('❌ BillingService.generateTrialBilling - Error:', error);
            throw new Error(error.message);
        }
    }

    /**
     * Check and update expired trial tenants
     */
    static async checkAndUpdateExpiredTrials() {
        try {
            console.log('🔍 BillingService.checkAndUpdateExpiredTrials');

            const TenantRepository = require('../repositories/tenantRepository');
            const SubscriptionRepository = require('../repositories/subscriptionRepository');
            const DowngradeService = require('./downgradeService');

            // Get trial tenants that have expired (trial_end_date passed)
            const expiredTrialTenants = await TenantRepository.getExpiredTrialTenants();
            console.log(`📊 Found ${expiredTrialTenants.length} expired trial tenants`);

            const results = [];

            for (const tenant of expiredTrialTenants) {
                try {
                    // Check if tenant has pending payment
                    const pendingPayments = await TenantPaymentRepository.getByTenant(tenant.id, 'pending');

                    if (pendingPayments && pendingPayments.length > 0) {
                        // Tenant has pending payment, keep as trial but mark as pending_payment
                        await TenantRepository.update(tenant.id, {
                            status: 'pending_payment',
                            subscription_status: 'pending_payment'
                        });
                        console.log(`✅ Updated tenant ${tenant.id} to pending_payment`);

                        results.push({
                            tenant_id: tenant.id,
                            action: 'pending_payment',
                            reason: 'has_pending_payment'
                        });
                    } else {
                        // ✅ NEW: No pending payment, downgrade to NotaFree instead of suspending
                        console.log(`🔄 Downgrading expired trial tenant ${tenant.id} to NotaFree`);

                        // Get active subscription (trial)
                        const activeSubscription = await SubscriptionRepository.getActiveByTenantId(tenant.id);

                        if (activeSubscription) {
                            // Downgrade to NotaFree
                            const downgradeResult = await DowngradeService.downgradeToNotaFree(tenant.id, activeSubscription);

                            if (downgradeResult) {
                                console.log(`✅ Successfully downgraded expired trial tenant ${tenant.id} to NotaFree`);
                                results.push({
                                    tenant_id: tenant.id,
                                    action: 'downgraded_to_notafree',
                                    reason: 'trial_expired_no_payment'
                                });
                            } else {
                                console.log(`⚠️ Failed to downgrade tenant ${tenant.id}, may already have NotaFree`);
                                results.push({
                                    tenant_id: tenant.id,
                                    action: 'skipped',
                                    reason: 'already_notafree_or_error'
                                });
                            }
                        } else {
                            console.log(`⚠️ Tenant ${tenant.id} has no active subscription, skipping downgrade`);
                            results.push({
                                tenant_id: tenant.id,
                                action: 'skipped',
                                reason: 'no_active_subscription'
                            });
                        }
                    }
                } catch (error) {
                    console.error(`❌ Error updating expired trial tenant ${tenant.id}:`, error);
                    results.push({
                        tenant_id: tenant.id,
                        action: 'error',
                        error: error.message
                    });
                }
            }

            return {
                processed: expiredTrialTenants.length,
                results: results
            };
        } catch (error) {
            console.error('❌ BillingService.checkAndUpdateExpiredTrials - Error:', error);
            throw new Error(error.message);
        }
    }
